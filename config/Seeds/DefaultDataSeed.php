/**
 * Default data seed: the reference data a fresh install needs.
 *
 * Roles, account types, payment methods and the category tree. Taken from the
 * production database (backup of 2026-09-28), ids are kept because other data
 * and the frontend refer to them.
 *
 * Runs automatically on container start (docker-entrypoint.sh). Every table is
 * only filled while it is empty, existing data is never touched — so this is
 * safe to run against an existing database as well.
 */
class DefaultDataSeed extends BaseSeed
{
    /**
     * Run Method.
     *
     * @return void
     */
    public function run(): void
    {
        // users.role_id defaults to 1 and references role: needed before the first user (bin/cake user_add).
        $this->seedTable('role', $this->roles());
        $this->seedTable('accounttype', $this->accountTypes());
        $this->seedTable('payment_method', $this->paymentMethods());
        // parent_id is a self-referencing FK: the rows are ordered by lft, so every parent
        // (smaller lft in a nested set) is inserted before its children.
        $this->seedTable('categories', $this->categories());
    }

    /**
     * I will insert the given $rows into $table, but only if the table is still empty.
     */
    private function seedTable(string $table, array $rows): void
    {
        $existing = $this->fetchRow("SELECT COUNT(*) AS cnt FROM `$table`");
        if ($existing && (int)$existing['cnt'] > 0) {
            return;
        }

        $this->table($table)->insert($rows)->save();
    }

